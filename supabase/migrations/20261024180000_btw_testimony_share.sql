-- Testimonies, closer to the hackathon brief (tracks/2-testimony-sharing):
-- guided questions whose answers become the story, a choice of who reads it
-- (only me / my church / my church and the team, who may feature it), a
-- parent or guardian's OK under 18, and a picture of the story people post
-- themselves (made in the browser; nothing is published by us).
alter table btw_testimonies add column if not exists answers jsonb;                -- { before, why, moment, advice, verse }
alter table btw_testimonies add column if not exists share text;                   -- 'me' | 'church' | 'baptize'
alter table btw_testimonies drop constraint if exists btw_testimonies_share_check;
alter table btw_testimonies add constraint btw_testimonies_share_check check (share in ('me', 'church', 'baptize'));
alter table btw_testimonies add column if not exists adult boolean;                -- 18 or older; asked unless share = 'me'
alter table btw_testimonies add column if not exists guardian_name text;           -- under 18: the parent or guardian who agreed
alter table btw_testimonies add column if not exists guardian_at timestamptz;
alter table btw_testimonies add column if not exists featured_at timestamptz;      -- starred by the team (share = 'baptize' only)

-- Stories saved before this were agreed for the church and the team to read.
update btw_testimonies set share = 'baptize' where share is null and submitted_at is not null;

