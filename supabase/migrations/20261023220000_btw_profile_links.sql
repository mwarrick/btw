-- A page where pastors see and update their own signup, reached by a link
-- sent with the DONE message: /p/<profile_key>. The key is random and
-- unguessable; it logs them in to that one signup and nothing else. Every
-- signup finished so far gets one now; new ones get theirs at DONE.
alter table btw_churches add column profile_key text unique;
update btw_churches set profile_key = replace(gen_random_uuid()::text, '-', '')
  where completed_at is not null and profile_key is null;

