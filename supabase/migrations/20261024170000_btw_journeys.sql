-- The first 30 days of faith (api/journey.js, public/journey.html at /journey
-- and /j/<key>, the church page's Newly baptized tab, Discipleship in /admin).
-- Online only: nothing is texted. Each day opens on its calendar day.
create table if not exists btw_journeys (
  id              bigint generated always as identity primary key,
  key             text not null unique,              -- the private link /j/<key>
  church_id       uuid references btw_churches(id) on delete set null,
  testimony_id    bigint references btw_testimonies(id) on delete set null,
  first_name      text not null,
  lang            text not null default 'en',
  phone           text,                              -- only when they let the church contact them
  contact_ok      boolean not null default false,
  consent_text    text,
  consent_at      timestamptz,
  started_on      date not null,                     -- day 1, in their time zone
  tz              text not null default 'UTC',
  done_days       int[] not null default '{}',
  next_step       text check (next_step in ('group', 'serve', 'class', 'unsure')),
  talked_at       timestamptz,                       -- the church pressed We talked
  seen_at         timestamptz,                       -- last time the page was opened
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create index if not exists btw_journeys_church_idx on btw_journeys (church_id);
alter table btw_journeys enable row level security;
create trigger btw_journeys_updated_at before update on btw_journeys for each row execute function btw_set_updated_at();

create table if not exists btw_checkins (
  id          bigint generated always as identity primary key,
  journey_id  bigint not null references btw_journeys(id) on delete cascade,
  day         int not null check (day in (7, 14, 21, 30)),
  answer      text not null check (answer in ('good', 'hard', 'question')),
  note        text,
  created_at  timestamptz not null default now(),
  unique (journey_id, day)
);
alter table btw_checkins enable row level security;

create table if not exists btw_journey_days (
  day         int not null check (day between 1 and 30),
  lang        text not null,
  theme       text not null,
  passage     text not null,
  note        text not null,
  question    text not null,
  step        text not null,
  updated_by  uuid references btw_users(id) on delete set null,
  updated_at  timestamptz not null default now(),
  primary key (day, lang)
);
alter table btw_journey_days enable row level security;
create trigger btw_journey_days_updated_at before update on btw_journey_days for each row execute function btw_set_updated_at();

alter table btw_churches add column if not exists weekly_note text;

alter table btw_web_requests drop constraint if exists btw_web_requests_kind_check;
alter table btw_web_requests add constraint btw_web_requests_kind_check check (kind in ('code', 'link', 'welcome', 'bot', 'story', 'journey'));

